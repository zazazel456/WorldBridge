def _tall_world(level=150):
    class Tall(SyntheticWorld):
        def read_chunk(self, dim, cx, cz):
            c = super().read_chunk(dim, cx, cz)
            c.blocks[1:level] = 1
            c.blocks[level - 3:level] = 3
            c.blocks[level] = 2
            return c
    return Tall(radius=1)


def test_anvil_targets_1_2_to_1_6_get_a_ring_up_to_256(tmp_path):
    from worldbridge.terrain import policy

    t = TargetSpec(family="java", java_mode="numeric", java_version_limit="1.6")
    assert policy.decide(t, True).kind == "ring"
    src = _tall_world()
    src.info.level["RandomSeed"] = src.info.level["RandomSeed"].__class__(-3878429724685138167)
    hub = str(tmp_path / "hub")
    w = JavaNumericWriter(hub, JavaWriteOptions(kind="anvil"), Progress())
    for cx, cz in src.chunk_coords(0):
        w.add_chunk(0, src.read_chunk(0, cx, cz))
    w.finish(src.info)
    out = str(tmp_path / "a16")
    convert(hub, out, TargetSpec(family="java", java_mode="numeric", java_version_limit="1.6"))
    world = JavaNumericWorld(out)
    coords = set(world.chunk_coords(0))
    assert len(coords) > 4 + 40
    # next to the converted mountain (ground at y 150) the ring rises above the generator's 128
    near = np.asarray(world.read_chunk(0, 1, 0).blocks)
    assert (near[140:, :, :2] != 0).any()
    # its outer edge is the game's own terrain
    far = max(x for x, z in coords if z == 0)
    gen, bio = ReleaseGenerator(-3878429724685138167, "1.6").chunk(far, 0)
    ring = world.read_chunk(0, far, 0)
    assert (np.transpose(gen, (2, 1, 0))[:, :, 15] == np.asarray(ring.blocks[:128])[:, :, 15]).all()
    assert (np.asarray(ring.biomes) == bio.T).all()


def test_terrain_and_caves_generated_by_minecraft_1_6_4():
    # chunk (0, 21) of seed -3878429724685138167, a jungle, as generated by Minecraft 1.6.4 (on the
    # 1,322 chunks of that world: biomes identical, air / water / rock identical in 98.97 % of the
    # blocks, the rest is the game's decoration: lakes, mineshafts, dungeons)
    blocks, biomes = ReleaseGenerator(-3878429724685138167, "1.6").chunk(0, 21)
    assert (biomes == 21).all()
    solid = np.isin(blocks, (1, 2, 3, 12, 13, 24))
    top = 127 - np.argmax(solid[:, :, ::-1], axis=2)
    # (the game's first row; at x 3 its decoration turned the top block into clay)
    assert top[:, 0].tolist() == [60, 60, 60, 60, 60, 60, 60, 61, 61, 61, 60, 60, 60, 60, 60, 60]
    air = np.isin(blocks[:, :, 5:50], (0, 10, 11))        # cave air and lava below y 50: block by block
    assert int(air.sum()) == 351
    for x, z, y in [(5, 0, 0), (3, 10, 4), (3, 9, 6), (4, 14, 7), (9, 12, 19), (2, 12, 20), (6, 10, 21), (12, 15, 22)]:
        assert air[x, z, y]
