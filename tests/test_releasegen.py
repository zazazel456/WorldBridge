def test_caves_and_ravines_as_generated_by_minecraft_1_0():
    # chunk (-5, 31) of seed -3878429724685138167, left undecorated by Minecraft 1.0: its cave air
    # below y 60 (3,329 blocks, a ravine through a cave) is identical to the game's, block by block
    blocks, _ = ReleaseGenerator(-3878429724685138167, "1.0").chunk(-5, 31)
    air = np.isin(blocks[:, :, 5:60], (0, 10))
    assert int(air.sum()) == 3329
    for x, z, y in [(0, 0, 24), (1, 7, 28), (2, 10, 12), (3, 11, 19), (4, 15, 11), (6, 3, 29), (7, 6, 17),
                    (8, 12, 15), (10, 4, 13), (11, 12, 12), (13, 3, 25), (14, 8, 4)]:
        assert air[x, z, y]


