def test_biomes_identical_to_cubiomes():
    for version, seed, x, z, a4, a1 in SNAP:
        s = Stack(version, seed)
        assert (s.biomes4(x // 4, z // 4, 12, 12) == np.array(a4)).all(), version
        assert (s.biomes(x, z, 24, 24) == np.array(a1)).all(), version


def test_terrain_generated_by_minecraft_1_0():
    # chunk (-20, 33) of seed -3878429724685138167 as generated by Minecraft 1.0 itself (surface
    # heights of its first row; validated on 1,023 game chunks)
    blocks, biomes = ReleaseGenerator(-3878429724685138167, "1.0").chunk(-20, 33)
    solid = np.isin(blocks, (1, 2, 3, 12, 13, 24))
    top = 127 - np.argmax(solid[:, :, ::-1], axis=2)
    assert top[:, 0].tolist() == REF_1_0_ROW
    assert blocks[:, :, 0].min() == 7                                         # bedrock floor


def test_1_1_targets_get_a_ring_without_raising_the_world(tmp_path):
    src = SyntheticWorld(radius=1)
    src.info.level["RandomSeed"] = src.info.level["RandomSeed"].__class__(12345)
    hub = str(tmp_path / "hub")
    w = JavaNumericWriter(hub, JavaWriteOptions(kind="anvil"), Progress())
    for cx, cz in src.chunk_coords(0):
        w.add_chunk(0, src.read_chunk(0, cx, cz))
    w.finish(src.info)
    out = str(tmp_path / "r11")
    convert(hub, out, TargetSpec(family="java", java_mode="mcregion", java_version_limit="1.1"))
    world = JavaNumericWorld(out)
    coords = set(world.chunk_coords(0))
    assert coords >= {(x, z) for x in range(-4, 4) for z in range(-4, 4)}
    far = max(x for x, z in coords if z == 0)
    ring = world.read_chunk(0, far, 0)
    assert not ring.terrain_populated
    gen, _ = ReleaseGenerator(12345, "1.1").chunk(far, 0)
    assert (np.transpose(gen, (2, 1, 0))[:, :, 15] == np.asarray(ring.blocks[:128])[:, :, 15]).all()
    # no +1 shift: that is only for the Alpha / Beta sea
    before = np.asarray(src.read_chunk(0, 0, 0).blocks[:128])
    after = np.asarray(world.read_chunk(0, 0, 0).blocks[:128])
    assert (before[1:] == after[1:]).all()


